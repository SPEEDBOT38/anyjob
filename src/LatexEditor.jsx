// The class and font files a template needs, for the downloadable LaTeX project.
async function projectFiles(t) {
  const files = [];
  for (const f of t.files) {
    const r = await fetch('/assets/latex/' + f);
    if (!r.ok) throw Error('Could not fetch ' + f);
    files.push({name: f.replace(/^[^/]+\//, ''), data: new Uint8Array(await r.arrayBuffer())});
  }
  return files;
}

export async function downloadProject(templateId, tex, title) {
  const t = templateById(templateId);
  const files = await projectFiles(t);
  const readme = `Compile main.tex with ${t.engine === 'xelatex' ? 'XeLaTeX' : 'pdfLaTeX'} (on Overleaf: Menu > Compiler > ${t.engine === 'xelatex' ? 'XeLaTeX' : 'pdfLaTeX'}).\nTemplate: ${t.name} by ${t.author} - ${t.repo} (${t.license}).\nGenerated by AnyJob.\n`;
  download(zip([{name: 'main.tex', data: tex}, ...files, {name: 'README.txt', data: readme}]), safeName(title) + '-latex.zip');
}

function CodeEditor({value, onChange, editorRef}) {
  const host = useRef(null);
  const view = useRef(null);
  const change = useRef(onChange);
  change.current = onChange;
  useEffect(() => {
    const v = new EditorView({
      doc: value,
      parent: host.current,
      extensions: [
        basicSetup,
        StreamLanguage.define(stex),
        EditorView.lineWrapping,
        keymap.of([{key: 'Mod-Enter', run: () => { host.current?.dispatchEvent(new CustomEvent('compile', {bubbles: true})); return true; }},
          {key: 'Mod-s', preventDefault: true, run: () => { host.current?.dispatchEvent(new CustomEvent('compile', {bubbles: true})); return true; }}]),
        EditorView.updateListener.of(u => { if (u.docChanged) change.current(u.state.doc.toString()); }),
        EditorView.theme({'&': {height: '100%'}, '.cm-scroller': {fontFamily: 'ui-monospace, SFMono-Regular, Menlo, Consolas, monospace', fontSize: '13px', lineHeight: '1.55'}}),
      ],
    });
    view.current = v;
    if (editorRef) editorRef.current = v;
    return () => v.destroy();
  }, []);
  useEffect(() => {
    const v = view.current;
    if (v && v.state.doc.toString() !== value) v.dispatch({changes: {from: 0, to: v.state.doc.length, insert: value}});
  }, [value]);
  return <div className="cm-host" ref={host} />;
}

// LaTeX source editor with real compilation (TeX Live on the server) and a page-accurate PDF preview.
export function LatexStudio({templateId, tex, onTex, generated, title, onPdf}) {
  const t = templateById(templateId);
  const editor = useRef(null);
  const box = useRef(null);
  const [state, setState] = useState({pdf: null, busy: false, errors: [], message: '', service: '', ms: 0});
  const [auto, setAuto] = useState(true);
  const [pane, setPane] = useState('code');
  const latest = useRef(tex);
  latest.current = tex;

  const compile = useCallback(async () => {
    const source = latest.current;
    setState(s => ({...s, busy: true, message: ''}));
    try {
      const out = await compileLatex(t.id, source);
      setState({pdf: out.bytes, busy: false, errors: [], message: '', service: out.service, ms: out.ms});
      onPdf && onPdf(out.bytes);
    } catch (e) {
      setState(s => ({...s, busy: false, errors: e.errors || [], message: e.message}));
    }
  }, [t.id]);

  useEffect(() => { compile(); }, [t.id]);
  useEffect(() => {
    if (!auto) return;
    const h = setTimeout(compile, 2200);
    return () => clearTimeout(h);
  }, [tex, auto]);
  useEffect(() => {
    const el = box.current;
    const fn = () => compile();
    el && el.addEventListener('compile', fn);
    return () => el && el.removeEventListener('compile', fn);
  }, [compile]);

  function insert([, before, after]) {
    const v = editor.current;
    if (!v) return;
    const {from, to} = v.state.selection.main;
    const sel = v.state.sliceDoc(from, to);
    v.dispatch({changes: {from, to, insert: before + sel + after}, selection: {anchor: from + before.length + sel.length}});
    v.focus();
  }
  function goTo(line) {
    const v = editor.current;
    if (!v || !line) return;
    const l = v.state.doc.line(Math.min(line, v.state.doc.lines));
    v.dispatch({selection: {anchor: l.from, head: l.to}, scrollIntoView: true});
    v.focus();
    setPane('code');
  }

  const edited = generated && tex !== generated;
  return <div className="studio" ref={box}>
    <div className="studio-bar">
      <button className="primary small" onClick={compile} disabled={state.busy} title="Compile (Ctrl+Enter)">{state.busy ? <Loader2 className="spin"/> : <Play/>}Compile</button>
      <label className="switch" title="Recompile 2 seconds after you stop typing"><input type="checkbox" checked={auto} onChange={e => setAuto(e.target.checked)}/><span/>Auto</label>
      <div className="snips">
        {[...(SNIPPETS[t.id] || []), ...GENERIC].map(s => <button key={s[0]} className="chip" onClick={() => insert(s)}>{s[0]}</button>)}
      </div>
      <span className="grow"/>
      {edited && <button className="ghost small" onClick={() => onTex(generated)} title="Discard LaTeX edits and rebuild from your CV"><RotateCcw/>Rebuild from CV</button>}
      <button className="ghost small" onClick={() => download(new Blob([tex], {type: 'text/x-tex'}), safeName(title) + '.tex')}><Download/>.tex</button>
      <button className="ghost small" onClick={() => downloadProject(t.id, tex, title).catch(e => setState(s => ({...s, message: e.message})))}><FileArchive/>Project .zip</button>
    </div>
    <div className="pane-toggle">
      <button aria-pressed={pane === 'code'} onClick={() => setPane('code')}><Code2/>LaTeX</button>
      <button aria-pressed={pane === 'pdf'} onClick={() => setPane('pdf')}><Eye/>PDF</button>
    </div>
    <div className={'studio-panes show-' + pane}>
      <div className="studio-code">
        {(state.errors.length > 0 || state.message) && <div className="tex-errors" role="alert">
          <b><AlertTriangle/>{state.message || 'LaTeX error'}{state.pdf ? ' The preview shows the last version that compiled.' : ''}</b>
          {state.errors.map((e, i) => <button key={i} onClick={() => goTo(e.line)}>{e.line ? 'Line ' + e.line + ': ' : ''}{e.message}</button>)}
        </div>}
        <CodeEditor value={tex} onChange={onTex} editorRef={editor}/>
      </div>
      <div className="studio-pdf">
        <div className="pdf-head"><span>{t.name} · {t.engine === 'xelatex' ? 'XeLaTeX' : 'pdfLaTeX'}</span>{state.busy ? <span className="busy"><Loader2 className="spin"/>Compiling…</span> : state.errors.length || state.message ? <span className="warn"><AlertTriangle/>Errors</span> : state.pdf ? <span className="ok"><Zap/>{(state.ms / 1000).toFixed(1)}s</span> : null}</div>
        {state.pdf ? <PdfView bytes={state.pdf}/> : <div className="pdf-empty">{state.busy ? 'Compiling your resume with TeX Live…' : 'Press Compile to see the PDF.'}</div>}
      </div>
    </div>
    {edited && <p className="hint"><Wand2/> You have edited the LaTeX by hand. Changes you make in the content editor will not show until you choose “Rebuild from CV”.</p>}
  </div>;
}
